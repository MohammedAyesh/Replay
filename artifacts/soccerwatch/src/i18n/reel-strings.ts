export type { ReelStrings };

export function useReelCopy(): ReelStrings & { locale: "en" | "ar"; isRtl: boolean } {
  const { locale } = useLocale();
  return { ...(locale === "ar" ? ar : en), locale, isRtl: locale === "ar" };
}

export type { GameStrings };

export function useGameCopy(): GameStrings & { locale: "en" | "ar"; isRtl: boolean } {
  const { locale } = useLocale();
  return { ...(locale === "ar" ? ar : en), locale, isRtl: locale === "ar" };
}

export function useCreativeMusicCopy(): CreativeMusicStrings & { locale: "ar" | "en" } {
  const { locale } = useLocale();
  return useConsoleWording({ ...(locale === "ar" ? ar : en), locale: locale === "ar" ? "ar" : "en" });
}

export const creativeMusicStrings = { en, ar };
